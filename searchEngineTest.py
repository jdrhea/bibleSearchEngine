import matplotlib.pyplot as plt
import json

with open("quran.json", "r", encoding="utf-8") as f:
    quran_data = json.load(f)

quran = {}
for surah in quran_data:
    quran[surah["transliteration"]] = {
        verse["id"]: verse["translation"]
        for verse in surah["verses"]
    }

# letters = ["a", "b", "c", "d", "e", "f", "g", "h", "i", "j", "k", "l", "m", "n", "o", "p", "q", "r", "s", "t", "u", "v", "w", "x", "y", "z"]
words = []
# for book in bible:
#     for chapter in bible[book]:
#         for verse in bible[book][chapter]:
#             words.extend(bible[book][chapter][verse].split())
for surah in quran:
    for verse in quran[surah]:
        words.extend(quran[surah][verse].split())
# for verse in text:
#     words.extend(text[verse].split())
wordsLength = len(words)

response = input("Search for: ").lower()
counts = {}
# for i in range(wordsLength):
#     response = words[i].lower()
results = 0
    # for book in bible:
    #     for chapter in bible[book]:
    #         for verse in bible[book][chapter]:
    #             if response in bible[book][chapter][verse].lower():
    # for surah in quran:
    #     for verse in quran[surah]:
    #         if response in quran[surah][verse].lower():
for j in range(wordsLength):
    if response == words[j].lower():
        # print(book, chapter, ":", verse)
        results += 1
print(str(results) + " of " + str(response) + " have been found")
    # for verse in text:
    #     if response in text[verse].lower():
    #         print(verse)
    #         results += 1
counts[response] = results
    #print(str(results) + " examples of "+ response + " have been found")

surface = "#fcfcfb"
primary_ink = "#0b0b0b"
muted_ink = "#898781"
gridline = "#e1e0d9"
baseline = "#c3c2b7"
bar_color = "#2a78d6"

top_n = 100
top_counts = dict(sorted(counts.items(), key=lambda item: item[1], reverse=True)[:top_n])
num_words = len(top_counts)
fig_width = max(12, num_words * 0.4)
fig, ax = plt.subplots(figsize=(fig_width, 6))
fig.patch.set_facecolor(surface)
ax.set_facecolor(surface)

ax.bar(top_counts.keys(), top_counts.values(), color=bar_color, width=0.6)

ax.set_title(f"References per Word (Top {num_words} of {len(counts)})", color=primary_ink, fontsize=14, pad=16)
ax.set_xlabel("Word", color=muted_ink)
ax.set_ylabel("Verses Containing Word", color=muted_ink)

label_size = 9 if num_words <= 30 else 7
ax.tick_params(axis="both", colors=muted_ink, labelsize=label_size)
plt.setp(ax.get_xticklabels(), rotation=90 if num_words > 15 else 0, ha="center")
for spine in ("top", "right", "left"):
    ax.spines[spine].set_visible(False)
ax.spines["bottom"].set_color(baseline)

ax.yaxis.grid(True, color=gridline, linewidth=0.8)
ax.set_axisbelow(True)

plt.tight_layout()
plt.show()